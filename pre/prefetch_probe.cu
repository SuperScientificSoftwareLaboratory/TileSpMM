#include "tilespmm_cuda.h"

static void probe_check(cudaError_t status, const char *operation)
{
    if (status != cudaSuccess)
    {
        fprintf(stderr, "Prefetch probe: %s: %s\n", operation, cudaGetErrorString(status));
        exit(EXIT_FAILURE);
    }
}

template <typename Kernel>
static void print_kernel(Kernel kernel, int BM, int BN, int columns, int threads)
{
    cudaFuncAttributes attr;
    probe_check(cudaFuncGetAttributes(&attr, kernel), "get kernel attributes");
    if (attr.numRegs <= 0 || threads > attr.maxThreadsPerBlock)
    {
        fprintf(stderr, "Invalid kernel resources for BM=%d, columns=%d.\n", BM, columns);
        exit(EXIT_FAILURE);
    }

    // The 32-column BM=8/16 kernels pack four independent tasks into one block.
    int tasks = columns == 32 && BM != 64 ? 4 : 1;
    int iteration_bytes = tasks * (BM * BN + BN * columns) * sizeof(MAT_VAL_TYPE);
    printf("    {%d, %d, %zu, %d}, // BM=%d, columns=%d\n",
           threads, attr.numRegs, attr.sharedSizeBytes, iteration_bytes, BM, columns);
}

int main(int argc, char **argv)
{
    bool key_only = argc == 3 && strcmp(argv[1], "--key") == 0;
    if (!key_only && argc != 2)
    {
        fprintf(stderr, "Usage: %s [--key] device_id\n", argv[0]);
        return EXIT_FAILURE;
    }
    int device = atoi(argv[key_only ? 2 : 1]);
    probe_check(cudaSetDevice(device), "select device");
    cudaDeviceProp prop;
    probe_check(cudaGetDeviceProperties(&prop, device), "get device properties");
    int driver_version, runtime_version;
    probe_check(cudaDriverGetVersion(&driver_version), "get driver version");
    probe_check(cudaRuntimeGetVersion(&runtime_version), "get runtime version");
    if (prop.multiProcessorCount <= 0 || prop.maxThreadsPerMultiProcessor <= 0 ||
        prop.sharedMemPerMultiprocessor == 0 || prop.maxBlocksPerMultiProcessor <= 0 ||
        prop.regsPerMultiprocessor <= 0 || prop.l2CacheSize <= 0)
    {
        fprintf(stderr, "Incomplete CUDA device resources.\n");
        return EXIT_FAILURE;
    }
    if (key_only)
    {
        printf("%d %d %d %d %zu %d %d %d %d %d\n",
               prop.major, prop.minor, prop.multiProcessorCount,
               prop.maxThreadsPerMultiProcessor, prop.sharedMemPerMultiprocessor,
               prop.maxBlocksPerMultiProcessor, prop.regsPerMultiprocessor,
               prop.l2CacheSize, driver_version, runtime_version);
        return EXIT_SUCCESS;
    }

    printf("// Generated by prefetch_probe.cu; regenerate with sh prepare_prefetch.sh [gpu_id].\n");
    printf("#pragma once\n\n");
    printf("struct PrefetchDeviceInfo\n{\n"
           "    int major, minor, sm_count, threads_per_sm;\n"
           "    size_t shared_bytes_per_sm;\n"
           "    int blocks_per_sm, registers_per_sm, l2_bytes;\n"
           "};\n\n");
    printf("struct PrefetchKernelInfo\n{\n"
           "    int threads, registers_per_thread;\n"
           "    size_t shared_bytes;\n"
           "    int iteration_bytes;\n"
           "};\n\n");
    printf("static const PrefetchDeviceInfo prefetch_device_info =\n"
           "    {%d, %d, %d, %d, %zu, %d, %d, %d};\n\n",
           prop.major, prop.minor, prop.multiProcessorCount,
           prop.maxThreadsPerMultiProcessor, prop.sharedMemPerMultiprocessor,
           prop.maxBlocksPerMultiProcessor, prop.regsPerMultiprocessor, prop.l2CacheSize);
    printf("static const PrefetchKernelInfo prefetch_kernel_info[6] =\n{\n");
#ifdef TFLOAT
    print_kernel(stir_spmm_cuda_kernel_v8_tf32_32<8, 8>, 8, 8, 32, 128);
    print_kernel(stir_spmm_cuda_kernel_v8_tf32<8, 8>, 8, 8, 64, 64);
    print_kernel(stir_spmm_cuda_kernel_v16_tf32_32<16, 8>, 16, 8, 32, 128);
    print_kernel(stir_spmm_cuda_kernel_v16_tf32<16, 8>, 16, 8, 64, 64);
    print_kernel(stir_spmm_cuda_kernel_v64_tf32_32<64, 16>, 64, 16, 32, 128);
    print_kernel(stir_spmm_cuda_kernel_v64_tf32<64, 16>, 64, 16, 64, 256);
#else
    print_kernel(stir_spmm_cuda_kernel_v8_32<8, 16>, 8, 16, 32, 128);
    print_kernel(stir_spmm_cuda_kernel_v8<8, 16>, 8, 16, 64, 64);
    print_kernel(stir_spmm_cuda_kernel_v16_32<16, 16>, 16, 16, 32, 128);
    print_kernel(stir_spmm_cuda_kernel_v16<16, 16>, 16, 16, 64, 64);
    print_kernel(stir_spmm_cuda_kernel_v64_32<64, 32>, 64, 32, 32, 128);
    print_kernel(stir_spmm_cuda_kernel_v64<64, 32>, 64, 32, 64, 256);
#endif
    printf("};\n\n");
    printf("static inline bool prefetch_device_matches(const cudaDeviceProp &prop)\n"
           "{\n"
           "    const PrefetchDeviceInfo &p = prefetch_device_info;\n"
           "    return prop.major == p.major && prop.minor == p.minor &&\n"
           "           prop.multiProcessorCount == p.sm_count &&\n"
           "           prop.maxThreadsPerMultiProcessor == p.threads_per_sm &&\n"
           "           prop.sharedMemPerMultiprocessor == p.shared_bytes_per_sm &&\n"
           "           prop.maxBlocksPerMultiProcessor == p.blocks_per_sm &&\n"
           "           prop.regsPerMultiprocessor == p.registers_per_sm &&\n"
           "           prop.l2CacheSize == p.l2_bytes;\n"
           "}\n");
    return ferror(stdout) ? EXIT_FAILURE : EXIT_SUCCESS;
}
